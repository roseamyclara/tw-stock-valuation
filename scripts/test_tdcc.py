fails: list[str] = []


def check(name: str, got, want) -> None:
    if got == want:
        print(f"  ok   {name}")
    else:
        fails.append(f"{name}: got {got!r}, want {want!r}")
        print(f"  FAIL {name}: got {got!r}, want {want!r}")


def synth(day: str, ratios: dict[str, float]) -> str:
    """把 {代號: 400張以上比例} 合成回 CSV：合計 1,000 股，級距 15 放大戶。"""
    lines = ["資料日期,證券代號,持股分級,人數,股數,占集保庫存數比例%"]
    for code, pct in ratios.items():
        lines.append(f"{day},{code:<6},15,1,{int(round(pct * 10))},{pct:.2f}")
        lines.append(f"{day},{code:<6},17,9,1000,100.00")
    return "\n".join(lines) + "\n"


